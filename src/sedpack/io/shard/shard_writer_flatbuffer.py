"""Dataset shard manipulation.

For information about FlatBuffers see https://flatbuffers.dev/
"""

from pathlib import Path

from flatbuffers import Builder
import numpy as np
import tenacity

from sedpack.io.compress import CompressedFile
from sedpack.io.metadata import Attribute, DatasetStructure
from sedpack.io.types import AttributeValueT, CompressionT
from sedpack.io.shard.shard_writer_base import ShardWriterBase
from sedpack.io.utils import hash_checksums_from_bytes

# Autogenerated from src/sedpack/io/flatbuffer/shard.fbs
import sedpack.io.flatbuffer.shardfile.Attribute as fbapi_Attribute
import sedpack.io.flatbuffer.shardfile.Example as fbapi_Example
import sedpack.io.flatbuffer.shardfile.Shard as fbapi_Shard


class ShardWriterFlatBuffer(ShardWriterBase):
    """Shard writing capabilities.
    """

    def __init__(self, dataset_structure: DatasetStructure,
                 shard_file: Path) -> None:
        """Collect information about a new shard.

        Args:

            dataset_structure (DatasetStructure): The structure of data being
            saved.

            shard_file (Path): Full path to the shard file.
        """
        assert dataset_structure.shard_file_type == "fb"

        super().__init__(
            dataset_structure=dataset_structure,
            shard_file=shard_file,
        )

    @staticmethod
    def _np_to_bytes(
        attribute: Attribute,
        value: AttributeValueT,
    ) -> bytes:
        """Turn a single AttributeValueT value into a sequence of bytes to be
        saved in a FlatBuffer shard.

        Args:

          attribute (Attribute): Description of the attribute defining dtype and
          shape.

          value (AttributeValueT): The actual value which is being represented.

        Raises: ValueError if the value cannot be cast to the correct dtype with
        the correct byteorder.
        """
        target_dtype = np.dtype(attribute.dtype).newbyteorder("<")
        value_np = np.asarray(value)

        # This is the workaround when the user passes a value which is
        # wrong dtype. Then a different number of bytes could be saved than
        # read causing unpredictable issues.
        if not np.can_cast(value_np, to=target_dtype, casting="safe"):
            raise ValueError("Cannot cast value of dtype "
                             f"{value_np.dtype} passed as "
                             f"{attribute = }")

        # Ensure little endian ("<") and C-contiguous order for FlatBuffers.
        return np.asarray(value_np, dtype=target_dtype, order="C").tobytes()

    @staticmethod
    def save_numpy_vector_as_bytearray(  # type: ignore[no-any-unimported]
        builder: Builder,
        attribute: Attribute,
        value: AttributeValueT,
    ) -> int:
        """Save a given array into a FlatBuffer as bytes. This is to ensure
        compatibility with types which are not supported by FlatBuffers (e.g.,
        np.float16).  The FlatBuffers schema must mark this vector as type
        bytes [byte] (see src/sedpack/io/flatbuffer/shard.fbs) since there is a
        distinction of how the length is being saved. The inverse of this
        function is
        `sedpack.io.flatbuffer.iterate.IterateShardFlatBuffer.decode_array`.

        If we have an array of np.int32 of 10 elements the FlatBuffers library
        would save the length as 10. Which is then impossible to read in Rust
        since the length and itemsize (sizeof of the type) are private. Thus we
        could not get the full array back. Thus we are saving the array as 40
        bytes. This function does not modify the `value`, and saves a flattened
        version of it. This function also saves the exact dtype as given by
        `attribute`. Bytes are being saved in little endian ("<") and
        c_contiguous ("C") order, same as with FlatBuffers. Alignment is set to
        `dtype.itemsize` as opposed to FlatBuffers choice of `dtype.alignment`.

        Args:

          builder (flatbuffers.Builder): The byte buffer being constructed.
          Must be initialized.

          attribute (Attribute): Description of this attribute (shape and
          dtype).

          value (AttributeValueT): The array to be saved. The shape should be
          as defined in `attribute` (will be flattened).

        Returns: The offset returned by `flatbuffers.Builder.EndVector`.

        Raises: ValueError if the dtype is unknown to NumPy.
        """
        # Not sure about flatbuffers.Builder __bool__ semantics.
        assert builder is not None

        # See `flatbuffers.builder.Builder.CreateNumpyVector`.
        byte_representation: bytes
        alignment: int
        match attribute.dtype:
            case "str":
                byte_representation = str(value).encode("utf-8")
                alignment = 16
            case "bytes":
                byte_representation = ShardWriterBase.attribute_value_to_bytes(
                    attribute=attribute,
                    value=value,
                )
                alignment = 16
            case _:
                try:
                    dtype = np.dtype(attribute.dtype)
                except Exception as exc:
                    raise ValueError(
                        f"Unsupported dtype {attribute.dtype}") from exc

                byte_representation = ShardWriterFlatBuffer._np_to_bytes(
                    attribute=attribute,
                    value=value,
                )
                alignment = dtype.itemsize

        # Total length of the array (in bytes).
        length: int = len(byte_representation)

        # Start a vector and move head accordingly.
        # FlatBuffers grows `builder.Bytes` backwards from the end toward index
        # 0. `StartVector` ensures capacity and aligns the write cursor
        # (`builder.Head()`, an index from the start of `builder.Bytes`), so
        # decrementing `head` by `length` reserves the slice for a bulk copy.
        builder.StartVector(
            elemSize=1,  # Storing bytes.
            numElems=length,
            alignment=alignment,  # Cautious alignment of the array.
        )
        builder.head = int(builder.Head() - length)

        # Copy values.
        builder.Bytes[builder.Head():builder.Head() +
                      length] = byte_representation

        # Not sure why the length is being set again (potentially allowing
        # recursive structures?).
        builder.vectorNumElems = length

        # Return the vector offset.
        # `EndVector` prepends the 4-byte element count (`vectorNumElems`) and
        # returns a `UOffsetT` offset measured from the *end* of `builder.Bytes`
        # (`len(builder.Bytes) - builder.Head()`), which remains valid if the
        # buffer is later reallocated at the front.
        return builder.EndVector()  # type: ignore[no-any-return]

    @tenacity.retry(
        wait=tenacity.wait_random(min=60, max=5 * 60),  # 1 to 5 minutes
        stop=tenacity.stop_after_attempt(10),
        retry=tenacity.retry_if_exception_type(OSError),
        reraise=True,
    )
    def _write_file(self, file_content: bytes) -> None:
        # Write the buffer into a file.
        with open(self._shard_file, "wb") as file:
            file.write(file_content)

    def _close(self) -> tuple[str, ...]:
        """Serialize buffered examples into a FlatBuffer shard file.
        """
        builder = Builder(0)

        # Since we are not saving attribute names we need to make sure to
        # iterate in the correct order.
        # FlatBuffers forbids nested table/vector construction (`Start...` /
        # `End...` cannot be interleaved). Child objects must be built bottom-up
        # first (byte vector -> Attribute table -> Attributes vector -> Example
        # table -> Examples vector -> Shard table) and referenced via their
        # buffer-end-relative `UOffsetT` offsets.
        examples: list[int] = []
        for example in self._examples:
            saved_attributes: list[int] = []
            for attribute in self.dataset_structure.saved_data_description:
                attribute_bytes: int = self.save_numpy_vector_as_bytearray(
                    builder=builder,
                    attribute=attribute,
                    value=example[attribute.name],
                )
                fbapi_Attribute.AttributeStart(builder)
                fbapi_Attribute.AttributeAddAttributeBytes(
                    builder,
                    attribute_bytes,
                )
                saved_attributes.append(fbapi_Attribute.AttributeEnd(builder))

            # Save attributes vector.
            # `PrependUOffsetTRelative` converts each buffer-end-relative offset
            # into a 4-byte self-relative pointer (`cursor - target`) and writes
            # it backwards (`head` decreases), so `reversed(...)` places element
            # 0 at the lowest address right after the vector length header.
            fbapi_Example.ExampleStartAttributesVector(builder,
                                                       len(saved_attributes))
            for offset in reversed(saved_attributes):
                builder.PrependUOffsetTRelative(offset)
            attributes_vector_offset = builder.EndVector()

            # Save the example.
            fbapi_Example.ExampleStart(builder)
            fbapi_Example.ExampleAddAttributes(builder,
                                               attributes_vector_offset)
            examples.append(fbapi_Example.ExampleEnd(builder))

        # Save examples vector.
        fbapi_Shard.ShardStartExamplesVector(builder, len(examples))
        for offset in reversed(examples):
            builder.PrependUOffsetTRelative(offset)
        examples_vector_offset = builder.EndVector()

        # Save the shard.
        fbapi_Shard.ShardStart(builder)
        fbapi_Shard.ShardAddExamples(builder, examples_vector_offset)
        shard = fbapi_Shard.ShardEnd(builder)

        # Finish the builder (prepends the root pointer to `shard`; `Output()`
        # slices the populated tail `builder.Bytes[builder.Head():]`).
        builder.Finish(shard)

        # Hash check-sums must be computed from already compressed file.
        file_content: bytes = CompressedFile(
            self.dataset_structure.compression).compress(bytes(
                builder.Output()))
        hash_checksums: tuple[str, ...] = hash_checksums_from_bytes(
            file_content=file_content,
            hashes=self.dataset_structure.hash_checksum_algorithms,
        )

        self._write_file(file_content=file_content)

        return hash_checksums

    @staticmethod
    def supported_compressions() -> list[CompressionT]:
        """Return a list of supported compression types.
        """
        return CompressedFile.supported_compressions()
